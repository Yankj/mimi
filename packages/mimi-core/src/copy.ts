export type StarterId = (typeof starters)[number]["id"];

/** Same order as ConversationStarterPrompts.ordered(hour:). */
export function orderedStarters(hour: number) {
  const byId = Object.fromEntries(starters.map((item) => [item.id, item])) as Record<StarterId, (typeof starters)[number]>;
  const order: StarterId[] =
    hour >= 5 && hour < 11
      ? ["schedule", "reminder", "meeting", "nearby", "breakdown", "writing"]
      : hour >= 11 && hour < 17
        ? ["meeting", "schedule", "nearby", "reminder", "breakdown", "writing"]
        : ["reminder", "schedule", "breakdown", "meeting", "writing", "nearby"];
  return order.map((id) => byId[id]);
}
